"""Run pipeline stages: python -m pipeline <stage> [--force]

Stages: 1 (fetch ICD-11), 2 (check the GBD files; fetched from a Claude session, see pipeline/STAGE2.md),
3 (build data/tree.json), 4 (cross-walk and burden), 8 (build site/public/map.json), or all.
Each stage skips itself when its outputs are newer than its inputs.
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

import yaml

from pipeline import chembl, crosswalk, fetch_icd11, gbd, icd11, proposals, site_data, tree
from pipeline.freshness import is_up_to_date

ROOT = Path(__file__).resolve().parent.parent
RAW_ICD11 = ROOT / "data" / "raw" / "icd11"
TABULATION = RAW_ICD11 / "tab" / "SimpleTabulation-ICD-11-MMS-en.txt"
MAPPING = RAW_ICD11 / "map" / "11To10MapToOneCategory.txt"
ICD10_CODES = RAW_ICD11 / "map" / "10To11MapToOneCategory.txt"
RAW_GBD = ROOT / "data" / "raw" / "gbd"
GBD_FILES = [RAW_GBD / n for n in ("fetch.json", "causes.csv", "icd_codes.csv", "dalys_level3.csv", "dalys_level4.csv")]
TREE = ROOT / "data" / "tree.json"
CROSSWALK = ROOT / "data" / "crosswalk.json"
REVIEW = ROOT / "data" / "crosswalk-review.yaml"
EXTRA_CODES = ROOT / "data" / "gbd-extra-codes.yaml"
BURDEN = ROOT / "data" / "burden.json"
RAW_CHEMBL = ROOT / "data" / "raw" / "chembl"
INDICATIONS = RAW_CHEMBL / "drug_indication.json"
PROPOSALS = ROOT / "data" / "proposals"
EVENTS = ROOT / "data" / "events.json"
MAP = ROOT / "site" / "public" / "map.json"
PKG = Path(__file__).resolve().parent


def write_json(path, data, indent=None):
    path.parent.mkdir(parents=True, exist_ok=True)
    separators = None if indent is not None else (",", ":")
    text = json.dumps(data, ensure_ascii=False, indent=indent, separators=separators)
    path.write_text(text + "\n", encoding="utf-8", newline="\n")


def stage1():
    fetch_icd11.fetch(RAW_ICD11)


def stage2():
    missing = [p.name for p in GBD_FILES if not p.exists()]
    if missing:
        sys.exit(f"  missing in data/raw/gbd/: {', '.join(missing)}. Stage 2 runs from a Claude session with "
                 "the IHME GBD connector: follow pipeline/STAGE2.md.")


def stage3():
    text = TABULATION.read_text(encoding="utf-8-sig")
    result = tree.build_tree(icd11.parse_tabulation(text), version=icd11.tabulation_version(text))
    write_json(TREE, result, indent=1)
    print(f"  {result['counts']}")


def read(path):
    return path.read_text(encoding="utf-8-sig")


def leaves(node):
    if "children" not in node:
        yield node
    for child in node.get("children", []):
        yield from leaves(child)


REVIEW_HEADER = """# Stage 4 ties: provinces whose ICD-10 code range splits evenly between GBD causes (docs/spec/v1.md).
# Each starts with the first candidate as a placeholder. Edit `resolution` to the cause_id you pick
# (or null to leave the province in fog), set `reviewed: true`, and rerun `python -m pipeline 4`.
# Generated by stage 4, which keeps your edits.
"""


def stage4():
    tree_data = json.loads(read(TREE))
    provinces = [{"uri": p["uri"], "code": p["code"], "title": p["title"]}
                 for chapter in tree_data["chapters"] for p in leaves(chapter)]
    hierarchy = read(RAW_GBD / "causes.csv")
    in_scope = gbd.causes_in_scope(hierarchy)
    icd = gbd.icd_rows(read(RAW_GBD / "icd_codes.csv"), yaml.safe_load(read(EXTRA_CODES)))
    groups = gbd.groups(hierarchy, icd, in_scope)
    causes = {**in_scope, **groups}
    dalys = gbd.dalys(read(RAW_GBD / "dalys_level3.csv"), read(RAW_GBD / "dalys_level4.csv"))
    dalys = {c: v for c, v in dalys.items() if c in in_scope}
    dalys.update({g: sum(dalys.get(m, 0.0) for m in v["members"]) for g, v in groups.items()})
    index = crosswalk.CauseIndex(icd, crosswalk.lookup_steps(set(in_scope), groups))
    universe = crosswalk.Icd10(icd11.parse_icd10_codes(read(ICD10_CODES)))
    review = (yaml.safe_load(read(REVIEW)) or []) if REVIEW.exists() else []
    result = crosswalk.build(provinces, icd11.parse_11_to_10(read(MAPPING)), universe, index, causes, dalys, review)

    # The review file is an input too, so write it before the outputs to keep them newer.
    REVIEW.write_text(REVIEW_HEADER + yaml.safe_dump(result["review"], sort_keys=False, allow_unicode=True, width=120),
                      encoding="utf-8", newline="\n")
    fetch = json.loads(read(RAW_GBD / "fetch.json"))
    meta = {"round": fetch["round"], "released": fetch["released"], "estimateYear": fetch["estimateYear"],
            "measure": "DALYs, global, all ages, both sexes", "fetched": fetch["fetched"], "citation": gbd.CITATION}
    write_json(CROSSWALK, {
        "note": crosswalk.NOTE,
        "sources": {"icd11": tree_data["icd11"]["release"], "who_map": icd11.RELEASE_URL + "mapping.zip",
                    "gbd": fetch["round"]},
        "provinces": result["crosswalk"],
    }, indent=1)
    write_json(BURDEN, {
        "note": "Province sizes: each GBD cause's DALYs split equally among the provinces cross-walked to it. "
                "Derived from GBD results; " + gbd.CITATION,
        "gbd": meta,
        "stats": result["stats"],
        "causes": {str(c): {**v, "group": causes[c]["group"]} for c, v in result["causes"].items()},
        "provinces": result["burden"],
    }, indent=1)
    for line in crosswalk.report(result["stats"], result["causes"]):
        print("  " + line)


def stage8():
    approved = proposals.load_approved(PROPOSALS) if PROPOSALS.exists() else {}
    events = json.loads(read(EVENTS)) if EVENTS.exists() else []
    updated = proposals.record_events(approved, events, datetime.date.today().isoformat())
    if updated != events:
        write_json(EVENTS, updated, indent=1)
        print(f"  {len(updated) - len(events)} status changes appended to data/events.json")
    print(f"  {len(approved)} approved GBD causes; their provinces are provisional")
    write_json(MAP, site_data.build_map(json.loads(read(TREE)), json.loads(read(CROSSWALK)), json.loads(read(BURDEN)),
                                        approved))


# number -> (name, run, inputs, outputs). A stage's own code counts as an input.
STAGES = {
    "1": ("fetch ICD-11", stage1, [], [TABULATION, MAPPING]),
    "2": ("check the GBD files", stage2, [], GBD_FILES),
    "3": ("build the tree", stage3, [TABULATION, PKG / "tree.py", PKG / "icd11.py"], [TREE]),
    "4": ("cross-walk and burden", stage4,
          [TREE, MAPPING, ICD10_CODES, *GBD_FILES, EXTRA_CODES, REVIEW, PKG / "crosswalk.py", PKG / "gbd.py"],
          [CROSSWALK, BURDEN]),
    "8": ("build site data", stage8,
          [TREE, CROSSWALK, BURDEN, PROPOSALS, *sorted(PROPOSALS.glob("*.yaml")), PKG / "site_data.py",
           PKG / "proposals.py"], [MAP]),
}


def main(argv=None):
    parser = argparse.ArgumentParser(prog="python -m pipeline", description=__doc__.splitlines()[0])
    parser.add_argument("stage", choices=[*STAGES, "all"])
    parser.add_argument("--force", action="store_true", help="run even if the outputs are up to date")
    args = parser.parse_args(argv)
    for number in STAGES if args.stage == "all" else [args.stage]:
        name, run, inputs, outputs = STAGES[number]
        if not args.force and is_up_to_date(outputs, inputs):
            print(f"stage {number} ({name}): up to date, skipped")
            continue
        print(f"stage {number} ({name})")
        run()
    return 0


if __name__ == "__main__":
    sys.exit(main())
